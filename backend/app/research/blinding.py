"""
Blinded presentation of the two plans for the RQ3 evaluation instrument.

What this module does
---------------------
* `blind_assignment(plan_id)` maps the participant-facing labels "A" and "B" to the internal conditions
  ('rule_based' / 'ai_personalized') of ONE stored plan. The mapping is pseudo-random per plan (a hash of the
  plan id and a fixed scheme string), reproducible by the researchers, and is used only on the server: it is
  never part of a participant-facing response.
* `neutral_plan_view(plan_json)` turns either stored plan JSON into one participant-facing view whose keys do
  not name the source (no 'rule_based', 'ai_', model, provider or fallback fields).

What it does NOT do (known limitations, to be stated wherever blinding is mentioned)
------------------------------------------------------------------------------------
* It blinds LABELS and field names, not CONTENT. The personalized plan carries extra text (overview, insights,
  per-workout warm-up and execution cues) that a participant may recognise as the generated variant. Removing
  that text would remove what the personalization criterion asks about.
* The label assignment is a hash, not a secret: anyone with the source code and a plan id can recompute it.
  "Limited access" therefore means "server-side only and not sent to participants", not cryptographic secrecy.
* It does not decide how participants obtain a plan id, how many plans each participant sees, or the order in
  which A and B are shown. Those are study-procedure decisions that are not made here.

Nothing in this module changes the rule engine, the validator, the stored plans or any frozen artifact.
"""
import hashlib
import re
from typing import Any, Dict, List, Optional

BLIND_SCHEME = "rq3-blind-v1"
LABELS = ("A", "B")

# A participant code is a random-looking token with no free text, so a name, e-mail address or phone number
# cannot be entered as a code. The code is generated by the client (see frontend BlindEvaluationPage) and is
# only used to pair the ratings of one participant.
PARTICIPANT_CODE_RE = re.compile(r"^P-[0-9A-F]{8}$")

# Free text that talks ABOUT how the plan was produced names the source. Any text block that matches is left out
# of the participant view (it is not rewritten). The block is generation meta-commentary, not training content,
# but this is a content-level removal and is stated as such. "baseline" alone is NOT treated as identifying
# because it also occurs in physiology wording ("baseline VDOT").
_SOURCE_WORDS = re.compile(
    r"\b(ai|a\.i\.|llm|gemini|openai|rule[- ]based|rule baseline|synthesi[sz]er|offline|fallback|language model)\b",
    re.IGNORECASE,
)


def _scrub(text: Any) -> Optional[str]:
    """Returns the text, or None if it names how the plan was produced."""
    if not isinstance(text, str) or not text.strip():
        return None
    return None if _SOURCE_WORDS.search(text) else text


_WORKOUT_FIELDS = (
    "day",
    "workout_type",
    "distance_km",
    "pace_target",
    "intensity_zone",
    "warmup_cooldown",
    "workout_execution",
    "recovery_instruction",
    "purpose",
)


def blind_assignment(plan_id: str) -> Dict[str, str]:
    """Server-side mapping label -> internal condition for one plan."""
    digest = hashlib.sha256(f"{BLIND_SCHEME}:{plan_id}".encode("utf-8")).digest()
    if digest[0] % 2 == 0:
        return {"A": "rule_based", "B": "ai_personalized"}
    return {"A": "ai_personalized", "B": "rule_based"}


def label_to_condition(plan_id: str, label: str) -> str:
    return blind_assignment(plan_id)[label]


_TEXT_FIELDS = ("warmup_cooldown", "workout_execution", "recovery_instruction", "purpose", "intensity_zone")


def _clean_workout(workout: Dict[str, Any]) -> Dict[str, Any]:
    out: Dict[str, Any] = {}
    for k in _WORKOUT_FIELDS:
        v = workout.get(k)
        if v in (None, ""):
            continue
        if k in _TEXT_FIELDS:
            v = _scrub(v)
            if v is None:
                continue
        out[k] = v
    return out


def _week_view(week: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "week_number": week.get("week_number"),
        "phase": week.get("phase"),
        "weekly_mileage_km": week.get("weekly_mileage_km"),
        "workouts": [_clean_workout(w) for w in week.get("workouts", [])],
    }


def neutral_plan_view(plan: Dict[str, Any]) -> Dict[str, Any]:
    """Participant-facing view of one stored plan; keys are identical for both conditions.

    Optional text blocks appear only when the stored plan has them. Their key names are neutral; the baseline's
    own 'focus_note' is not shown, so that no key exists for only one condition by name alone.
    """
    view: Dict[str, Any] = {"weeks": [_week_view(w) for w in plan.get("weeks", [])]}
    overview = _scrub(plan.get("coach_overview"))
    if overview:
        view["overview"] = overview
    insights = {k: _scrub(v) for k, v in (plan.get("personalized_insights") or {}).items()}
    insights = {k: v for k, v in insights.items() if v}
    if insights:
        view["insights"] = insights
    notes = [t for t in (_scrub(n) for n in (plan.get("ai_personalization_summary") or [])) if t]
    if notes:
        view["notes"] = notes
    why = plan.get("why_this_plan_was_generated") or {}
    rationale: Dict[str, Any] = {}
    factors = [t for t in (_scrub(f) for f in (why.get("key_influencing_factors") or [])) if t]
    if factors:
        rationale["factors"] = factors
    additions = _scrub(why.get("ai_personalization_additions"))
    if additions:
        rationale["additions"] = additions
    if rationale:
        view["rationale"] = rationale
    return view


def blinded_plans(plan_id: str, rule_based_plan: Dict[str, Any], ai_plan: Dict[str, Any]) -> List[Dict[str, Any]]:
    sources = {"rule_based": rule_based_plan, "ai_personalized": ai_plan}
    assignment = blind_assignment(plan_id)
    return [{"label": label, **neutral_plan_view(sources[assignment[label]])} for label in LABELS]


def is_valid_participant_code(code: Optional[str]) -> bool:
    return bool(code) and bool(PARTICIPANT_CODE_RE.match(code))
